// Build desktop/src/generated/index.ts from the files ts-rs emitted.
//
// ts-rs writes one file per type and does not emit a barrel, so this script
// orders the re-exports to keep the generated diff readable. It runs from
// scripts/generate-types.sh after cargo, and from `pnpm run check:types` before
// the comparison (ADR-0040).
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "src", "generated");

const names = readdirSync(dir)
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .map((file) => file.slice(0, -3))
  .sort((a, b) => a.localeCompare(b));

const banner = `// Barrel for the ts-rs output. Generated by scripts/generate-index.mjs.
// Do not edit by hand: run desktop/scripts/generate-types.sh instead.
`;

const body = names.map((name) => `export type { ${name} } from "./${name}";`).join("\n");
writeFileSync(join(dir, "index.ts"), `${banner}\n${body}\n`);
console.log(`wrote ${names.length} re-exports`);
